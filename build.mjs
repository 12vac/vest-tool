// Dependency-free build: bundles the CommonJS modules of src/ into a single dist/vest-tool.user.js.
// Each file becomes a function (module, exports, require); .css files become strings.
// After the build, safety checks: if one fails the file is not written.
import { readFileSync, writeFileSync, mkdirSync, readdirSync, statSync } from 'node:fs';
import { join, relative, dirname, posix } from 'node:path';
import { fileURLToPath } from 'node:url';
import vm from 'node:vm';

const ROOT = dirname(fileURLToPath(import.meta.url));
const SRC = join(ROOT, 'src');
const OUT = join(ROOT, 'dist', 'vest-tool.user.js');
const ENTRY = 'main.js';
const ALLOWED_HOSTS = ['next.vestmarkets.com', 'api-gateway.hz.vestmarkets.com', 'ws.hz.vestmarkets.com'];

const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));

function walk(dir) {
  return readdirSync(dir).flatMap((n) => {
    const p = join(dir, n);
    return statSync(p).isDirectory() ? walk(p) : [p];
  });
}

const files = walk(SRC)
  .map((p) => relative(SRC, p).split('\\').join('/'))
  .filter((p) => p.endsWith('.js') || p.endsWith('.css'))
  .sort();

if (!files.includes(ENTRY)) throw new Error('missing src/' + ENTRY);

// Every require('./x') must point to an existing file: error at build time, not in the browser.
const REQ_RE = /require\(\s*'([^']+)'\s*\)/g;
const resolve = (from, rel) => {
  let p = posix.normalize(posix.join(posix.dirname(from), rel));
  if (!/\.(js|css)$/.test(p)) p += '.js';
  return p;
};
for (const f of files.filter((f) => f.endsWith('.js'))) {
  const code = readFileSync(join(SRC, f), 'utf8');
  for (const m of code.matchAll(REQ_RE)) {
    if (!m[1].startsWith('.')) throw new Error(`${f}: require('${m[1]}') not relative (no external packages)`);
    const t = resolve(f, m[1]);
    if (!files.includes(t)) throw new Error(`${f}: require('${m[1]}') -> ${t} does not exist`);
  }
}

const defs = files
  .map((f) => {
    const code = readFileSync(join(SRC, f), 'utf8');
    const body = f.endsWith('.css') ? `module.exports = ${JSON.stringify(code)};` : code;
    return `  ${JSON.stringify(f)}: function (module, exports, require) {\n${body}\n  },`;
  })
  .join('\n');

const meta = readFileSync(join(SRC, 'meta.txt'), 'utf8').replace('{{VERSION}}', pkg.version).trimEnd();

const out = `${meta}

// Generated by build.mjs: do not edit by hand, edit src/ and rebuild.
(function () {
  'use strict';
  if (window.top !== window) return; // never inside the chart iframe
  const __defs = {
${defs}
  };
  const __cache = {};
  const __norm = (p) => {
    const out = [];
    for (const s of p.split('/')) {
      if (s === '..') out.pop();
      else if (s && s !== '.') out.push(s);
    }
    return out.join('/');
  };
  const __load = (id) => {
    if (__cache[id]) return __cache[id].exports;
    const def = __defs[id];
    if (!def) throw new Error('missing module: ' + id);
    const module = (__cache[id] = { exports: {} });
    const dir = id.includes('/') ? id.slice(0, id.lastIndexOf('/')) : '';
    def(module, module.exports, (rel) => {
      let p = __norm((dir ? dir + '/' : '') + rel);
      if (!/\\.(js|css)$/.test(p)) p += '.js';
      return __load(p);
    });
    return module.exports;
  };
  __load(${JSON.stringify(ENTRY)}).start(${JSON.stringify(pkg.version)});
})();
`;

// ── safety checks on the final file
const problems = [];
for (const m of out.matchAll(/\b(?:https?|wss?):\/\/([a-z0-9.-]+)/gi)) {
  if (!ALLOWED_HOSTS.includes(m[1].toLowerCase())) problems.push('host not allowed: ' + m[0]);
}
const FORBIDDEN = [
  ['@updateURL', /@updateURL/],
  ['@downloadURL', /@downloadURL/],
  ['@require', /@require/],
  ['eval(', /\beval\s*\(/],
  ['new Function', /new\s+Function\s*\(/],
  ['plain-text JWT', /eyJ[A-Za-z0-9_-]{8,}/],
  ['GM_xmlhttpRequest', /GM_xmlhttpRequest/],
  ['sendBeacon', /sendBeacon/],
  ['import()', /\bimport\s*\(/],
];
for (const [name, re] of FORBIDDEN) if (re.test(out)) problems.push('forbidden: ' + name);
if (!/@grant\s+none/.test(out)) problems.push('missing @grant none');
if (!/@noframes/.test(out)) problems.push('missing @noframes');

// one kind of line ending only (LF, as Tampermonkey stores scripts): some source files are CRLF
const lf = out.replace(/\r\n?/g, '\n');

// the file must be valid JavaScript: a syntax error here would silently disable the script on Vest
try {
  new vm.Script(lf, { filename: 'vest-tool.user.js' });
} catch (e) {
  problems.push('syntax: ' + e.message);
}

if (problems.length) {
  console.error('BUILD REFUSED:\n - ' + problems.join('\n - '));
  process.exit(1);
}

mkdirSync(dirname(OUT), { recursive: true });
writeFileSync(OUT, lf);
console.log(`ok: ${relative(ROOT, OUT)} (${files.length} modules, ${(lf.length / 1024).toFixed(1)} KB, v${pkg.version})`);
